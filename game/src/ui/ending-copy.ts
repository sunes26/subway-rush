/**
 * 엔딩 표현 계층의 **공용 문장·배지**.
 *
 * ■ 왜 별도 모듈인가
 *
 * 이 문장들은 오래 `ui/screens.ts` 안에 있었다. 결과 화면만 쓰던 시절에는 그게
 * 맞았는데, 도감 상세가 **같은 설명**을 보여 주게 되면서 두 화면이 같은 표를
 * 봐야 해졌다. 복사해 두면 반드시 갈라진다 — 한쪽만 고치는 날이 온다.
 *
 * ■ ★ `data/endings.ts` 는 건드리지 않는다
 *
 * 저기는 **판정**이다(조건식·우선순위·`line`). 여기는 **표현**이다(설명·배지).
 * 둘을 섞으면 문구를 다듬을 때마다 판정 파일을 열게 되고, 그러다 조건이 딸려
 * 바뀐다. 실제로 그 경계 덕분에 엔딩 판정을 upstream 것으로 통째로 받으면서도
 * 화면 문구는 이쪽에서 유지할 수 있었다.
 *
 * ■ 문장 원칙 (이 파일의 모든 문자열에 적용된다)
 *
 *   · **일어난 일만 적는다.** 교훈·위로·칭찬을 붙이지 않는다.
 *   · **조건을 흘리지 않는다.** 개수·임계값·규칙은 적지 않는다 — 도감이
 *     체크리스트가 되면 수집이 아니라 심부름이 된다.
 *   · 짧고 건조하게. 재치가 설명을 대신하지 않는다.
 *
 * `tests/unit/ending-tone.test.ts` 가 위로·교훈 어휘를 문자열로 막는다.
 */

import type { EndingDef } from '../data/endings'
import type { EndingId } from '../state/types'

/** 엔딩 톤 — `data/endings.ts` 의 `tone` 과 같은 축이다 */
export type EndingTone = EndingDef['tone']

/**
 * 결과 배지.
 *
 * 색이 아니라 **글자가 상태를 말한다** — 색만으로 구분하면 색각 이상이나
 * 저대비 환경에서 세 상태가 같은 화면이 된다. 색은 거들 뿐이다.
 */
const STATUS: Readonly<Record<EndingTone, string>> = {
  success: 'SUCCESS',
  fail: 'GAME OVER',
  hidden: 'SPECIAL',
}

/**
 * 두 엔딩만 **자기 이름을 배지 자리에 쓴다.**
 *
 * E-04 는 톤이 `success` 라 `SUCCESS` 가 뜬다. 맞는 말이지만, 닫히는 문에 몸을
 * 밀어 넣은 판과 여유롭게 걸어 들어간 판이 **같은 단어로 끝난다.** 어떻게 탔는지가
 * 이 게임에서 가장 자주 갈리는 결과인데 그 차이가 화면에 안 남는다.
 * E-08 도 마찬가지다 — `GAME OVER` 는 왜 끝났는지를 안 말한다.
 *
 * **새 톤을 만들지 않는다** — 색은 톤이 그대로 정하므로 JUST IN TIME 은 초록,
 * WRONG WAY 는 빨강이다. 바뀌는 것은 글자뿐이라 색각 이상 환경에서도 안 뭉갠다.
 */
const STATUS_BY_ID: Readonly<Partial<Record<EndingId, string>>> = {
  'E-04': 'JUST IN TIME',
  'E-08': 'WRONG WAY',
}

/** 이 엔딩의 배지 글자 */
export const badgeOf = (id: EndingId, tone: EndingTone): string =>
  STATUS_BY_ID[id] ?? STATUS[tone]

/**
 * 도감이 쓰는 **상태 라벨** — 언제나 셋 중 하나다.
 *
 * ⚠ 한때 슬롯이 좁다고 `GAME OVER` 를 `OVER` 로 줄여 썼다. 그러면 같은 화면 안에서
 *   슬롯은 `OVER`, 상세는 `GAME OVER` 라 **같은 상태가 두 이름으로** 보인다.
 *   줄여야 할 만큼 좁다면 그건 라벨이 아니라 레이아웃 문제다 — 슬롯을 키웠다.
 *
 * ⚠ `badgeOf` 와 다르다. 저쪽은 결과 화면용이라 E-04 `JUST IN TIME`,
 *   E-08 `WRONG WAY` 처럼 **그 판이 어떻게 끝났는지**를 말한다. 도감은 목록이라
 *   18칸이 같은 축으로 분류돼야 하므로 톤 셋으로만 적는다.
 */
export const statusOf = (tone: EndingTone): string => STATUS[tone]

