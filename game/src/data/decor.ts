import { FLOOR } from './world'
import type { ItemId } from '../state/types'

export type Decor = Readonly<{
  id: string
  /** 어떤 아이템 메시를 빌려 쓰는가 (`data/items.ts` 의 `node`) */
  item: ItemId
  x: number
  y: number
  /** 밑면이 놓이는 높이 */
  z: number
  /** 세우는 방향(rad). 같은 각으로 여럿 두면 복제한 티가 난다 */
  yaw: number
  /**
   * 눕히거나 뒤집는 각(rad, 모델 로컬 X축). 없으면 0.
   * `Interactable.propPitch` 와 같은 규약이다 — 두 표가 같은 메시를 빌려 쓰므로
   * **같은 물건은 같은 값**이어야 한다(우산 다섯 자루가 서로 반대로 꽂히면 안 된다).
   */
  pitch?: number
}>

